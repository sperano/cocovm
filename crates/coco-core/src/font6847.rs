//! Motorola VDG character generators — the internal font ROMs of the two
//! chips CoCo 1/2 shipped: the original MC6847 ([`MC6847_FONT`]) and the
//! later MC6847T1 ([`MC6847T1_FONT`]), selectable per-machine via
//! [`crate::config::VDGVariant`]. Both draw an 8×12 cell, 12 bytes per
//! character (one per raster row), glyph occupying the low 6 bits (leftmost
//! pixel = bit mask 0x80 >> col).
//!
//! The two chips draw the *same* 64 uppercase/symbol glyphs ($00-$3F) at
//! different row offsets within the 12-row cell: the plain MC6847
//! ([`MC6847_FONT`]) occupies rows 3-10 (top 2 and bottom 2 rows always
//! blank — MAME `vdg_fontdata8x12`), while the MC6847T1 ([`MC6847T1_FONT`])
//! occupies rows 1-8, freeing rows 8-11 for the descenders of the T1-only
//! lowercase glyphs (g/j/p/q/y).
//!
//! [`MC6847T1_FONT`] additionally has 32 more entries (index 64-95) for the
//! T1's true-lowercase mode: '^', then 'a'-'z', then `{ | } ~ _`. Real CoCo
//! screen codes only ever select these via [`crate::video`]'s special-case
//! true-lowercase path (codes $00-$1F when PIA1 $FF22 GM0 is set and the T1
//! chip is installed) — codes $20-$3F never reach index 64+ on either chip.
//! The plain MC6847 has no equivalent: codes $00-$1F always draw the
//! corresponding inverse-video uppercase glyph regardless of any PIA1 bit
//! (MAME's `character_map` ctor gates `is_lower_case` on `is_mc6847t1`).
//!
//! SOURCE / LICENSING: both tables are taken from MAME's `mc6847.cpp`
//! (`vdg_fontdata8x12` and `vdg_t1_fontdata8x12`, GPL-2.0+). They are
//! included here pending a licensing decision for the project — see the note
//! in the module tree. Do not ship as-is without resolving the license.

